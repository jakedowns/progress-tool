'use strict';

/**
 * Optional local task-list mirror.
 *
 * When enabled, every state-store write also renders the current session's
 * task tree to a Markdown checklist. It is deterministic: relay ticks that
 * only change progress/updatedAt produce identical Markdown, so the file is
 * not rewritten at telemetry rates. The rendered content is cached per file,
 * so an unchanged tree does not even re-read the file.
 *
 * Enable with PROGRESS_TASKLIST=1.
 *
 * Location (PROGRESS_TASKLIST_LOCATION):
 *   0 = <cwd>/.progress/tasklist-<session>.md
 *   1 = <cwd>/tasklist-<session>.md            (default)
 *   2 = ~/.opencode-progress/tasklist-<session>.md
 *
 * View (PROGRESS_TASKLIST_MODE, or the palette preference):
 *   "ui"  = hide dismissed/cleared entries and roll child status up (default)
 *   "raw" = include dismissed/cleared entries and show stored status
 *
 * Detail (PROGRESS_TASKLIST_DETAIL):
 *   "code"    = fenced code block (default, safe)
 *   "escaped" = inline Markdown-escaped text
 *   "raw"     = unescaped text (opt-in; untrusted content may render links)
 *
 * Relay entries (PROGRESS_TASKLIST_RELAY_LEVEL):
 *   0 (default) = omit relay-created command entries
 *   1           = mirror every relay entry
 *   2           = mirror relay entries only while their current status is error
 */

const fs = require('fs');
const os = require('os');
const path = require('path');

const DEFAULT_ORDER = 'newest-first';
const DEFAULT_LOCATION = 1;
const DEFAULT_MODE = 'ui';
const DEFAULT_DETAIL = 'code';
const TRUTHY = new Set(['1', 'true', 'yes', 'on']);
const MODES = new Set(['ui', 'raw']);
const DETAILS = new Set(['code', 'escaped', 'raw']);
const LOCATIONS = new Set([0, 1, 2]);

/** First line of every mirror. Used to refuse clobbering non-mirror files. */
const MIRROR_MARKER = '<!-- generated by progress-tool task-list mirror -->';

const contentCache = new Map();
const statusCache = new Map();
const statusAbsent = new Set();
const warned = new Set();

function isTruthy(value) {
  return typeof value === 'string' && TRUTHY.has(value.trim().toLowerCase());
}

/**
 * Normalize relayMirrorLevel. Numeric 0/1/2 is the documented form; accept
 * the obvious aliases so hand-written MCP env stays readable.
 */
function normalizeRelayMirrorLevel(value) {
  const text = String(value ?? '').trim().toLowerCase();
  if (text === 'log' || text === 'all') return 1;
  if (text === 'err' || text === 'error' || text === 'errors') return 2;
  const numeric = Number(text);
  return numeric === 1 || numeric === 2 ? numeric : 0;
}

function normalizeLocation(value) {
  const numeric = Number(String(value ?? '').trim());
  return Number.isInteger(numeric) && LOCATIONS.has(numeric) ? numeric : DEFAULT_LOCATION;
}

function normalizeMode(value) {
  const mode = String(value ?? '').trim().toLowerCase();
  return MODES.has(mode) ? mode : DEFAULT_MODE;
}

function normalizeDetail(value) {
  const detail = String(value ?? '').trim().toLowerCase();
  return DETAILS.has(detail) ? detail : DEFAULT_DETAIL;
}

function normalizeOrder(value) {
  return String(value ?? '').trim().toLowerCase() === 'oldest-first'
    ? 'oldest-first'
    : DEFAULT_ORDER;
}

function homeDir(env = process.env) {
  return env.HOME || env.USERPROFILE || os.homedir();
}

function defaultStateFile(env = process.env) {
  return env.PROGRESS_STATE_PATH || path.join(homeDir(env), '.opencode-progress-state.json');
}

/** Preferences and status sit next to the state file, never in the repo. */
function taskListPrefsPath(stateFile = defaultStateFile()) {
  return path.join(path.dirname(stateFile), '.opencode-progress-tasklist-prefs.json');
}

function taskListStatusPath(stateFile = defaultStateFile()) {
  return path.join(path.dirname(stateFile), '.opencode-progress-tasklist-status.json');
}

function readModePreference(stateFile) {
  try {
    const parsed = JSON.parse(fs.readFileSync(taskListPrefsPath(stateFile), 'utf8'));
    return parsed && typeof parsed === 'object' && MODES.has(parsed.mode) ? parsed.mode : undefined;
  } catch {
    return undefined;
  }
}

function readTaskListStatus(stateFile = defaultStateFile()) {
  try {
    const parsed = JSON.parse(fs.readFileSync(taskListStatusPath(stateFile), 'utf8'));
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch {
    return null;
  }
}

function statusSignature(status) {
  return JSON.stringify({
    enabled: status.enabled,
    mode: status.mode,
    detail: status.detail,
    location: status.location,
    order: status.order,
    file: status.file,
    sessionID: status.sessionID,
  });
}

function writeTaskListStatus(stateFile, status) {
  const file = taskListStatusPath(stateFile);
  const signature = statusSignature(status);
  if (statusCache.get(file) === signature) return;
  const body = `${JSON.stringify({ ...status, updatedAt: Date.now() }, null, 2)}\n`;
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
    fs.writeFileSync(tmp, body, { encoding: 'utf8', mode: 0o600 });
    fs.renameSync(tmp, file);
    statusCache.set(file, signature);
    statusAbsent.delete(file);
  } catch (error) {
    warnOnce(`${file}:status`, `task-list status write failed for ${file}: ${error}`);
  }
}

function removeTaskListStatus(stateFile) {
  const file = taskListStatusPath(stateFile);
  statusCache.delete(file);
  if (statusAbsent.has(file)) return;
  try {
    fs.unlinkSync(file);
  } catch (error) {
    if (error && error.code === 'ENOENT') statusAbsent.add(file);
  }
}

function warnOnce(key, message) {
  if (warned.has(key)) return;
  warned.add(key);
  console.error(`[progress] ${message}`);
}

function taskListConfig(env = process.env, cwd = process.cwd(), stateFile) {
  const resolvedStateFile = stateFile || defaultStateFile(env);
  const enabled = isTruthy(env.PROGRESS_TASKLIST);
  return {
    enabled,
    location: normalizeLocation(env.PROGRESS_TASKLIST_LOCATION),
    mode: enabled
      ? readModePreference(resolvedStateFile) || normalizeMode(env.PROGRESS_TASKLIST_MODE)
      : normalizeMode(env.PROGRESS_TASKLIST_MODE),
    detail: normalizeDetail(env.PROGRESS_TASKLIST_DETAIL),
    order: normalizeOrder(env.PROGRESS_TASKLIST_ORDER),
    relayMirrorLevel: normalizeRelayMirrorLevel(env.PROGRESS_TASKLIST_RELAY_LEVEL),
    sessionID: String(env.PROGRESS_SESSION_ID || env.OPENCODE_SESSION_ID || '').trim(),
    cwd,
    stateFile: resolvedStateFile,
  };
}

function safeName(value) {
  const cleaned = String(value || 'shared')
    .replace(/[^A-Za-z0-9._-]+/g, '_')
    .slice(0, 120);
  return cleaned || 'shared';
}

function taskListFileName(sessionID) {
  return `tasklist-${safeName(sessionID)}.md`;
}

function resolveTaskListPath(config) {
  const name = taskListFileName(config.sessionID);
  if (config.location === 0) return path.join(config.cwd, '.progress', name);
  if (config.location === 2) return path.join(homeDir(), '.opencode-progress', name);
  return path.join(config.cwd, name);
}

function timestamp(value) {
  const numeric = Number(value);
  return Number.isFinite(numeric) && numeric > 0 ? numeric : 0;
}

function iso(value) {
  const numeric = timestamp(value);
  return numeric ? new Date(numeric).toISOString() : '';
}

function oneLine(value, max = 300) {
  const text = String(value ?? '')
    .replace(/\s+/g, ' ')
    .trim();
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

function escapeLineStart(value) {
  return value.replace(/^(\s*)([#>\-+=])/, '$1\\$2');
}

function escapeInline(value, max = 200) {
  return escapeLineStart(oneLine(value, max).replace(/([\\`*_[\]()!<>~|#])/g, '\\$1'));
}

/** Headings keep `_` literal (session ids are `ses_…`) but escape the rest. */
function escapeHeading(value) {
  return oneLine(value, 120).replace(/([\\`*[\]()!<>~|#])/g, '\\$1');
}

function keyOf(entry) {
  return `${entry && entry.sessionId ? entry.sessionId : ''}:${entry && entry.id}`;
}

function sortEntries(entries, order) {
  const direction = order === 'oldest-first' ? 1 : -1;
  return entries.slice().sort((left, right) => {
    const byTime = (timestamp(left.createdAt) - timestamp(right.createdAt)) * direction;
    if (byTime !== 0) return byTime;
    return keyOf(left).localeCompare(keyOf(right));
  });
}

function visibleEntries(state, sessionID, mode, relayMirrorLevel) {
  const all = Object.values((state && state.entries) || {}).filter(
    (entry) => entry && typeof entry === 'object'
  );
  return all.filter((entry) => {
    // Legacy unscoped entries belong to every session view.
    if (sessionID && entry.sessionId && entry.sessionId !== sessionID) return false;
    // Relay-created command entries are high-volume telemetry. Level 0 hides
    // them, level 1 keeps everything, and level 2 keeps only current errors.
    if (entry.relay) {
      if (relayMirrorLevel === 1) {
        // Keep.
      } else if (relayMirrorLevel === 2) {
        if (entry.status !== 'error') return false;
      } else {
        return false;
      }
    }
    if (mode === 'ui' && (entry.dismissed || entry.cleared)) return false;
    return true;
  });
}

/**
 * Effective status for the visible tree: bottom-up roll-up in UI mode, stored
 * status in raw mode. Mirrors the GUI/TUI roll-up (error > running > waiting >
 * pending > done) so the Markdown does not claim a parent is running when every
 * child is done.
 */
function effectiveStatuses(entries, byKey, children, mode) {
  const cache = new Map();
  if (mode === 'raw') {
    for (const entry of entries) cache.set(keyOf(entry), entry.status || 'unknown');
    return cache;
  }
  const visiting = new Set();
  const visit = (key) => {
    if (cache.has(key)) return cache.get(key);
    if (visiting.has(key)) return byKey.get(key)?.status || 'running';
    const entry = byKey.get(key);
    if (!entry) return 'unknown';
    visiting.add(key);
    let status = entry.status || 'running';
    const kids = children.get(key) || [];
    if (kids.length) {
      const statuses = kids.map((child) => visit(keyOf(child)));
      if (statuses.includes('error')) status = 'error';
      else if (statuses.includes('running')) status = 'running';
      else if (statuses.includes('waiting')) status = 'waiting';
      else if (statuses.includes('pending')) status = 'pending';
      else if (statuses.every((child) => child === 'done')) status = 'done';
    }
    visiting.delete(key);
    cache.set(key, status);
    return status;
  };
  for (const entry of entries) visit(keyOf(entry));
  return cache;
}

function detailLines(detail, mode, indent) {
  const text = oneLine(detail, 500);
  if (!text) return [];
  if (mode === 'code') {
    let fence = '```';
    while (text.includes(fence)) fence += '`';
    return [`${indent}${fence}text`, `${indent}${text}`, `${indent}${fence}`];
  }
  if (mode === 'escaped') return [`${indent}${escapeInline(text, 500)}`];
  return [`${indent}${text}`];
}

/**
 * Render a state document as Markdown. Pure: no filesystem access.
 */
function renderTaskList(state, options = {}) {
  const sessionID = options.sessionID ? String(options.sessionID) : '';
  const order = normalizeOrder(options.order);
  const mode = normalizeMode(options.mode);
  const detail = normalizeDetail(options.detail);
  const relayMirrorLevel = normalizeRelayMirrorLevel(options.relayMirrorLevel);
  const entries = visibleEntries(state, sessionID, mode, relayMirrorLevel);

  const byKey = new Map(entries.map((entry) => [keyOf(entry), entry]));
  const children = new Map();
  const roots = [];
  for (const entry of entries) {
    const parentKey = entry.parentId
      ? `${entry.sessionId ? entry.sessionId : ''}:${entry.parentId}`
      : '';
    if (parentKey && byKey.has(parentKey) && parentKey !== keyOf(entry)) {
      const list = children.get(parentKey) || [];
      list.push(entry);
      children.set(parentKey, list);
    } else {
      roots.push(entry);
    }
  }

  const effective = effectiveStatuses(entries, byKey, children, mode);
  const lines = [
    MIRROR_MARKER,
    `# Task list — ${escapeHeading(sessionID || 'shared session')}`,
    '',
    `_Mirrored from progress-tool. ${mode === 'ui' ? 'UI view' : 'Raw view'}; ${
      order === 'oldest-first' ? 'oldest' : 'newest'
    } first. Do not edit by hand._`,
    '',
  ];

  if (entries.length === 0) {
    lines.push('_No tasks yet._');
  } else {
    const seen = new Set();
    const renderEntry = (entry, depth) => {
      const key = keyOf(entry);
      if (seen.has(key) || depth > 20) return;
      seen.add(key);
      const status = effective.get(key) || entry.status || 'unknown';
      const checked = status === 'done' ? 'x' : ' ';
      const created = iso(entry.createdAt);
      const updated = iso(entry.statusUpdatedAt || entry.updatedAt || entry.createdAt);
      const flags = [];
      if (entry.dismissed) flags.push('dismissed');
      if (entry.cleared) flags.push('cleared');
      const meta = [
        status,
        created ? `created ${created}` : '',
        updated ? `updated ${updated}` : '',
        ...flags,
      ]
        .filter(Boolean)
        .join(' · ');
      lines.push(
        `${'  '.repeat(depth)}- [${checked}] **${escapeInline(
          entry.title || entry.id
        )}** — ${meta}`
      );
      const indent = '  '.repeat(depth + 1);
      for (const line of detailLines(entry.detail, detail, indent)) lines.push(line);
      for (const child of sortEntries(children.get(key) || [], order)) {
        renderEntry(child, depth + 1);
      }
    };
    for (const root of sortEntries(roots, order)) renderEntry(root, 0);
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Render and write the mirror when it changed. Best-effort: never throws.
 * Returns { written, file?, reason?, error? }.
 */
function syncTaskList(state, options = {}) {
  const stateFile = options.stateFile || defaultStateFile(options.env || process.env);
  const config = taskListConfig(options.env || process.env, options.cwd || process.cwd(), stateFile);
  if (options.sessionID) config.sessionID = String(options.sessionID);
  if (!config.enabled) {
    removeTaskListStatus(stateFile);
    return { written: false, reason: 'disabled' };
  }

  const file = resolveTaskListPath(config);
  const content = renderTaskList(state, config);
  writeTaskListStatus(stateFile, {
    enabled: true,
    mode: config.mode,
    detail: config.detail,
    location: config.location,
    order: config.order,
    file,
    sessionID: config.sessionID,
  });

  const cached = contentCache.get(file);
  if (cached === content) {
    try {
      const stat = fs.statSync(file);
      if (stat.isFile() && stat.size === Buffer.byteLength(content)) {
        return { written: false, file, reason: 'unchanged' };
      }
    } catch {
      // Missing or unreadable: fall through and recreate it.
    }
  }

  let previous;
  try {
    previous = fs.readFileSync(file, 'utf8');
  } catch {
    // First write, or unreadable: fall through.
  }
  if (previous === content) {
    contentCache.set(file, content);
    return { written: false, file, reason: 'unchanged' };
  }
  if (previous !== undefined && previous.trim() !== '' && !previous.startsWith(MIRROR_MARKER)) {
    warnOnce(
      `${file}:refuse`,
      `task-list mirror refuses to overwrite ${file}: missing "${MIRROR_MARKER}" marker`
    );
    return { written: false, file, reason: 'not-a-mirror' };
  }

  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const tmp = `${file}.tmp-${process.pid}-${Date.now()}`;
    fs.writeFileSync(tmp, content, { encoding: 'utf8', mode: 0o600 });
    fs.renameSync(tmp, file);
    contentCache.set(file, content);
    return { written: true, file };
  } catch (error) {
    warnOnce(`${file}:write`, `task-list mirror write failed for ${file}: ${error}`);
    return { written: false, file, reason: 'error', error: String(error) };
  }
}

